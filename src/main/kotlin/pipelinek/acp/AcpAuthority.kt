package pipelinek.acp

import com.agentclientprotocol.model.PermissionOption
import com.agentclientprotocol.model.RequestPermissionOutcome
import com.agentclientprotocol.model.RequestPermissionResponse
import com.agentclientprotocol.model.ToolCallId
import com.agentclientprotocol.model.ToolKind
import java.util.concurrent.ConcurrentHashMap
import kotlinx.coroutines.CompletableDeferred

/**
 * The permission authority of PKH-134: the declared runtime policy behind the client's
 * answer to `session/request_permission`, and the one place the intersection is computed.
 *
 * ## The intersection, in order
 * AC#1 says the effective decision is profile ∩ authority ∩ human-policy, over the options
 * the agent actually offered:
 *
 * 1. the PROFILE is the ceiling (PKH-133's rule: a promise, and READONLY promises no
 *    effects past reading);
 * 2. the AUTHORITY is the runtime policy the pipeline declared through the DSL — without a
 *    declaration nothing is granted, which keeps PKH-132's deny-by-default as the default;
 * 3. the HUMAN leg fails closed while the published seam offers no authorized-interaction
 *    capability to plugins: a rule that requires a human denies rather than auto-approving
 *    in the human's name (the PKACP-SDK-02 pattern — absent machinery is named, never
 *    pretended; and "no confundir respuesta humana con autorización" cuts both ways);
 * 4. the offered OPTIONS are the last word: a grant selects an optionId the agent offered,
 *    never one the client invented — an invented id is a protocol lie that could authorize
 *    an action the agent never proposed.
 *
 * Commands generated by the agent are never policy: the only inputs here are the declared
 * authority, the negotiated profile and the wire's own option list.
 */

/** The closed vocabulary of declared effect classes; the v1 [ToolKind]s map into it. */
@kotlinx.serialization.Serializable
enum class AcpToolEffect {
    /** sees data, changes nothing: READ, SEARCH, FETCH. */
    READ,

    /** changes workspace state: EDIT, DELETE, MOVE. */
    MUTATE,

    /** runs a command: EXECUTE. */
    EXECUTE,

    /** everything the v1 kinds carry that is none of the above: THINK, SWITCH_MODE, OTHER. */
    MISC,
}

/**
 * The permission authority a pipeline DECLARED for one `acpTask` delegation.
 *
 * Durability note (PKH-133's codec rule applies): this travels inside [AcpTaskInput], so it
 * is serializable, closed-vocabulary, and additive — an absent authority decodes to null and
 * means deny-by-default, exactly as if the field had never existed.
 */
@kotlinx.serialization.Serializable
data class AcpAuthority(
    /** the effect classes this delegation may grant; anything absent is denied. */
    val allowedEffects: List<AcpToolEffect>,
    /**
     * effect classes whose grant additionally requires an authorized human answer.
     *
     * With no human-interaction seam published to plugins, a human-required effect DENIES
     * (see the class doc); the declaration is honoured as "not without a person", which is
     * the safe half of the promise, and the refusal says so.
     */
    val humanRequiredEffects: List<AcpToolEffect> = emptyList(),
)

/**
 * The pure decision of AC#1 — profile ∩ authority ∩ offered options. Testable without a
 * process, a pipe, or the SDK's session machinery.
 */
object AcpPermissionPolicy {

    /** The total mapping from the v1 wire kinds into the declared effect vocabulary. */
    fun effectOf(kind: ToolKind): AcpToolEffect = when (kind) {
        ToolKind.READ, ToolKind.SEARCH, ToolKind.FETCH -> AcpToolEffect.READ
        ToolKind.EDIT, ToolKind.DELETE, ToolKind.MOVE -> AcpToolEffect.MUTATE
        ToolKind.EXECUTE -> AcpToolEffect.EXECUTE
        ToolKind.THINK, ToolKind.SWITCH_MODE, ToolKind.OTHER -> AcpToolEffect.MISC
    }

    /**
     * The intersection at the ceiling level: may this profile even host this authority?
     *
     * A READONLY delegation declaring mutate/execute authority is a contradiction the seam
     * refuses BEFORE launch (PKH-133's precedent: a promise the target cannot keep is named
     * as a refusal, not silently dropped at decision time). WRITE_RESTRICTED is already
     * refused wholesale by [AcpTaskIsolation.validate], so the only honourable ceiling here
     * is READONLY-with-read-only-authority.
     */
    fun ceilingViolation(profile: AcpTaskProfile, authority: AcpAuthority): Boolean =
        profile == AcpTaskProfile.READONLY &&
            authority.allowedEffects.any { it != AcpToolEffect.READ }

    /** The client's answer to one `session/request_permission`, in wire types. */
    suspend fun decide(
        profile: AcpTaskProfile,
        authority: AcpAuthority?,
        kind: ToolKind,
        offeredOptions: List<PermissionOption>,
    ): RequestPermissionResponse {
        val effect = effectOf(kind)
        val granted = authority != null &&
            effect in authority.allowedEffects &&
            // (1) the profile ceiling: READONLY hosts no effect past reading.
            !(profile == AcpTaskProfile.READONLY && effect != AcpToolEffect.READ) &&
            // (3) the human leg: fail-closed while the seam is absent — see the class doc.
            effect !in authority.humanRequiredEffects
        if (!granted) {
            return RequestPermissionResponse(RequestPermissionOutcome.Cancelled)
        }
        // (4) only an option the agent offered can be selected; allow-once first, because
        // granting persistence the pipeline never negotiated is a wider door than the grant.
        val option = offeredOptions.firstOrNull {
            it.kind == com.agentclientprotocol.model.PermissionOptionKind.ALLOW_ONCE
        } ?: offeredOptions.firstOrNull {
            it.kind == com.agentclientprotocol.model.PermissionOptionKind.ALLOW_ALWAYS
        } ?: return RequestPermissionResponse(RequestPermissionOutcome.Cancelled)
        return RequestPermissionResponse(RequestPermissionOutcome.Selected(option.optionId))
    }
}

/**
 * The ledger of permission requests the client has received and not yet answered.
 *
 * AC#1's last clause: after a cancel, pending `session/request_permission` requests of the
 * session must be answered with the Cancelled outcome. The ACP SDK pinned here (0.34.0) does
 * NOT do this itself — upstream fixed it only after this release (agentclientprotocol/
 * acp-kotlin-sdk#156) — so the plugin owns the ledger. The permission handler registers
 * BEFORE deciding and awaits the registered deferred, which makes the cancel path live
 * today: a session/cancel that overtakes an in-flight decision resolves the open entry to
 * Cancelled over the wire BEFORE session/cancel is said, so the agent resolves its own
 * request instead of hanging until the process is reaped. When the human-interaction seam
 * arrives (later tasks of this front), the same await is what parks the answer on the
 * person instead of the policy — which is exactly why the ledger is the right shape now.
 */
class AcpPermissionLedger {
    private val pending = ConcurrentHashMap<ToolCallId, CompletableDeferred<RequestPermissionResponse>>()

    fun register(toolCallId: ToolCallId, response: CompletableDeferred<RequestPermissionResponse>) {
        pending[toolCallId] = response
    }

    fun release(toolCallId: ToolCallId) {
        pending.remove(toolCallId)
    }

    /**
     * Answers every outstanding request with Cancelled; returns how many were resolved.
     * Idempotent and drained-on-use: the second call (close, or a repeated cancel) answers
     * nothing because the first one took the entries out. A deferred that already carries
     * its answer is only removed — the first completion wins.
     */
    fun cancelOutstanding(): Int {
        var answered = 0
        for (toolCallId in pending.keys.toList()) {
            val response = pending.remove(toolCallId) ?: continue
            if (response.complete(RequestPermissionResponse(RequestPermissionOutcome.Cancelled))) {
                answered++
            }
        }
        return answered
    }
}
